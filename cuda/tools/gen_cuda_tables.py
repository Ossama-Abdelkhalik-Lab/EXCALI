"""Generate cuda/excali_tables_cuda.h from EXCALI's own compiled constants.

Builds a small Fortran program that includes src/excali_tables.inc and
EXCALI's constant definitions (the lines of src/excali_solver.f90 from the
dp kind to the include), dumps every value's bit pattern, and writes the
values as C hex-float literals, so the C++ port uses exactly the bits gfortran
produces. The trig tables are stored as the positive half (nodes 1-4 and the
endpoint): cos/cosh are even and sin/sinh odd, which the script checks bit for
bit before dropping the negative half.

Usage (from the repository root): python3 cuda/tools/gen_cuda_tables.py [gfortran]
"""
import os, struct, subprocess, sys, tempfile

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
fc = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("FC", "gfortran")
src = open(os.path.join(root, "src", "excali_solver.f90")).read().split("\n")
a = next(i for i, l in enumerate(src) if "integer,parameter :: dp=real64" in l)
b = next(i for i, l in enumerate(src) if "include 'excali_tables.inc'" in l)
hdr = "\n".join(src[a:b + 1])
f64 = ["pi", "sqrt2", "rsqrt2", "rf", "cser", "pser2", "u8", "w8", "c8f", "s8f", "ch8f", "sh8f", "bb",
       "tabe_z0", "tabe_z1", "tabh_s1", "tabh_u0", "xser", "xwin"]
f32 = ["tabe", "tabh", "mr_q", "mr_c", "mr_s", "bt_a", "bt_b"]
calls = "\n".join(f"   call w64('{n}',reshape([{n}],[size([{n}])]))" for n in f64) + "\n" + \
        "\n".join(f"   call w32('{n}',reshape({n},[size({n})]))" for n in f32)
prog = f"""module tdump
   use iso_fortran_env, only: real32, real64, int64, int32
   implicit none
{hdr}
end module
program dump
   use tdump
   implicit none
   integer::u,i
   open(newunit=u,file='tables_dump.txt',status='replace')
{calls}
   close(u)
contains
   subroutine w64(nm,x)
      character(*)::nm; real(real64)::x(:)
      write(u,'(a,1x,i0,a)')nm,size(x),' f64'
      do i=1,size(x); write(u,'(z16.16)')transfer(x(i),0_int64); enddo
   end subroutine
   subroutine w32(nm,x)
      character(*)::nm; real(real32)::x(:)
      write(u,'(a,1x,i0,a)')nm,size(x),' f32'
      do i=1,size(x); write(u,'(z8.8)')transfer(x(i),0_int32); enddo
   end subroutine
end program
"""
with tempfile.TemporaryDirectory() as d:
    open(os.path.join(d, "dump.f90"), "w").write(prog)
    subprocess.check_call([fc, "-O0", "-ffree-line-length-none", "-I", os.path.join(root, "src"),
                           "dump.f90", "-o", "dump"], cwd=d)
    subprocess.check_call(["./dump"], cwd=d)
    lines = open(os.path.join(d, "tables_dump.txt")).read().split()

vals, i = {}, 0
while i < len(lines):
    name, n, kind = lines[i], int(lines[i + 1]), lines[i + 2]
    raw = lines[i + 3:i + 3 + n]
    if kind == "f64":
        vals[name] = [struct.unpack(">d", bytes.fromhex(h))[0] for h in raw]
    else:
        vals[name] = [struct.unpack(">f", bytes.fromhex(h))[0] for h in raw]
    i += 3 + n

# Trig tables (10 nodes x 63 widths, column-major): keep nodes 1-4 and 9 (u=+1).
POS, NEG = [0, 1, 2, 3, 8], [4, 5, 6, 7, 9]
half = {}
for nm, odd in (("c8f", False), ("s8f", True), ("ch8f", False), ("sh8f", True)):
    full = vals[nm]
    h = []
    for k in range(63):
        col = full[10 * k:10 * k + 10]
        for p, q in zip(POS, NEG):
            assert col[q] == (-col[p] if odd else col[p]), (nm, k, p)
        h += [col[p] for p in POS]
    half[nm] = h

def lit64(x):
    return x.hex() if x != 0 else ("-0x0p+0" if str(x).startswith("-") else "0x0p+0")
def lit32(x):
    return (x.hex() if x != 0 else "0x0p+0") + "f"
def arr(f, ctype, name, xs, lit):
    f.write(f"EXCALI_TABLE {ctype} {name}[{len(xs)}] = {{\n")
    for j in range(0, len(xs), 4):
        f.write("  " + ", ".join(lit(x) for x in xs[j:j + 4]) + ",\n")
    f.write("};\n")

out = os.path.join(root, "cuda", "excali_tables_cuda.h")
with open(out, "w") as f:
    f.write("// Generated by cuda/tools/gen_cuda_tables.py from src/excali_tables.inc and\n"
            "// src/excali_solver.f90 constants; do not edit. Bit-exact copies of gfortran's values.\n"
            "#pragma once\n#ifndef EXCALI_TABLE\n#define EXCALI_TABLE static const\n#endif\n")
    for nm in ("pi", "sqrt2", "rsqrt2", "tabe_z0", "tabe_z1", "tabh_s1", "tabh_u0", "xser", "xwin"):
        f.write(f"#define EXC_{nm.upper()} {lit64(vals[nm][0])}\n")
    for nm in ("rf", "cser", "pser2", "u8", "w8", "bb"):
        arr(f, "double", "exc_" + nm, vals[nm], lit64)
    f.write("// Half trig tables: [k*5 + p], p = 0..3 positive nodes, 4 the endpoint u = 1.\n")
    for nm in ("c8f", "s8f", "ch8f", "sh8f"):
        arr(f, "double", "exc_" + nm[:-1] + "h", half[nm], lit64)
    for nm in ("tabe", "tabh"):
        arr(f, "float", "exc_" + nm, vals[nm], lit32)

# Byte accounting for the report.
B = lambda nm, w: len(vals[nm]) * w
zr32 = B("tabe", 4) + B("tabh", 4)
mr32 = B("mr_q", 4) + B("mr_c", 4) + B("mr_s", 4) + B("bt_a", 4) + B("bt_b", 4)
small = 8 * (len(vals["bb"]) + len(vals["rf"]) + len(vals["cser"]) + len(vals["pser2"]) + len(vals["u8"]) + len(vals["w8"]))
trig_full = 8 * 4 * 630; trig_half = 8 * 4 * 315
print(f"zero-rev starters {zr32} B, multi-rev tables {mr32} B, small constants {small} B, "
      f"trig full {trig_full} B, trig half {trig_half} B")
print(f"zero-rev port (half trig): {zr32 + small + trig_half} B; full suite half trig: {zr32 + mr32 + small + trig_half} B; "
      f"full suite full trig: {zr32 + mr32 + small + trig_full} B")
print("wrote", out)
